export const UNRELEASED_DIR = 'unreleased';

/** Reads `<root>/changes/`. Anything that is not a fragment, a release.json or the README is refused. */
export function loadChangeSet(root: string): ChangeSet {
	const changesDir = join(root, 'changes');
	const rel = (p: string) => relative(root, p);
	const set: ChangeSet = { unreleased: [], releases: [] };
	// Dotfiles (Finder's .DS_Store) are machine noise, never content.
	const visible = (name: string) => !name.startsWith('.');
	for (const entry of readdirSync(changesDir).filter(visible).sort()) {
		const path = join(changesDir, entry);
		if (!statSync(path).isDirectory()) {
			if (entry === 'README.md') continue;
			fail(
				rel(path),
				'unexpected file — changes/ holds only README.md and one directory per release',
			);
		}
		const fragments: Fragment[] = [];
		for (const file of readdirSync(path).filter(visible).sort()) {
			const filePath = join(path, file);
			if (file === 'release.json') continue;
			if (!file.endsWith('.md'))
				fail(rel(filePath), 'unexpected file — a release directory holds *.md and release.json');
			fragments.push(parseFragment(rel(filePath), readFileSync(filePath, 'utf8')));
		}
		if (entry === UNRELEASED_DIR) {
			if (existsSync(join(path, 'release.json')))
				fail(rel(path), 'unreleased/ cannot carry a release.json');
			set.unreleased = fragments;
			continue;
		}
		const releaseFile = join(path, 'release.json');
		if (!existsSync(releaseFile)) fail(rel(path), 'a release directory needs its release.json');
		const release = parseRelease(rel(releaseFile), readFileSync(releaseFile, 'utf8'));
		if (release.version !== entry) {
			fail(
				rel(releaseFile),
				`version '${release.version}' does not match its directory '${entry}'`,
			);
		}
		set.releases.push({ release, fragments });
	}
	return set;
}

/** Every ledger id, read from each entry's h1 (`# <id> — <title>`), the ledger's own key. */
export function wireContractIds(root: string): string[] {
	const dir = join(root, 'engineering', 'wire_contract');
	const ids: string[] = [];
	for (const file of readdirSync(dir).sort()) {
		if (!file.endsWith('.md')) continue;
		const h1 = readFileSync(join(dir, file), 'utf8').split('\n', 1)[0] ?? '';
		const id = /^# (WC-\S+) — /.exec(h1)?.[1];
		if (id === undefined || !WC_ID_RE.test(id))
			fail(`engineering/wire_contract/${file}`, 'h1 carries no ledger id');
		ids.push(id);
	}
	return ids;
}

/** Ledger ids no release has claimed yet — what the next release will adopt. */
export function unreleasedWireContract(set: ChangeSet, allIds: string[]): string[] {
	const claimed = new Set(set.releases.flatMap((r) => r.release.wire_contract));
	return allIds.filter((id) => !claimed.has(id)).sort();
}

/** The one page, as the repository's current files define it. */
export function renderFromRepo(root: string): string {
	const set = loadChangeSet(root);
	return renderChangeLog(set, unreleasedWireContract(set, wireContractIds(root)));
}

