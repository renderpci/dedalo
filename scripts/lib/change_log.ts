const INTRO = [
	'What changed in each Dédalo v7 release, newest first. Every change is filed under',
	'who it affects — **users** of the application, **administrators** who install and',
	'run it, and **developers** who build on its API. A release that needs something',
	'from you when you update says so first, in an *Action needed* box.',
	'',
	"Each release's *Wire contract* list names the deliberate changes to the API's wire",
	'shape by the id under which the source tree records each one',
	'(`engineering/wire_contract/`).',
].join('\n');

function indent(body: string): string {
	return body
		.split('\n')
		.map((line) => (line.trim() === '' ? '' : `    ${line}`))
		.join('\n');
}

function byNewest(a: Fragment, b: Fragment): number {
	if (a.date !== b.date) return a.date < b.date ? 1 : -1;
	return a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0;
}

function renderFragments(fragments: Fragment[]): string[] {
	const out: string[] = [];
	const breaking = fragments.filter((f) => f.breaking).sort(byNewest);
	if (breaking.length > 0) {
		out.push('!!! warning "Action needed when you update"');
		out.push('');
		for (const f of breaking) out.push(`    - ${f.title}`);
		out.push('');
	}
	for (const audience of AUDIENCES) {
		const mine = fragments.filter((f) => f.audience === audience);
		if (mine.length === 0) continue;
		out.push(`### ${AUDIENCE_HEADINGS[audience]}`, '');
		for (const type of TYPES) {
			const group = mine.filter((f) => f.type === type).sort(byNewest);
			if (group.length === 0) continue;
			out.push(`#### ${TYPE_HEADINGS[type]}`, '');
			for (const f of group) {
				out.push(`- **${f.title}**${f.breaking ? ' *(action needed)*' : ''}`, '');
				out.push(indent(f.body), '');
				if (f.wc.length > 0) {
					out.push(indent(`Wire contract: ${f.wc.map((id) => `\`${id}\``).join(', ')}.`), '');
				}
			}
		}
	}
	return out;
}

function renderWireContract(ids: string[]): string[] {
	if (ids.length === 0) return [];
	const count = `${ids.length} ${ids.length === 1 ? 'entry' : 'entries'}`;
	return [
		`??? note "Wire contract — ${count}"`,
		'',
		...[...ids].sort().map((id) => `    - \`${id}\``),
		'',
	];
}

export function renderChangeLog(set: ChangeSet, unreleasedWc: string[]): string {
	const out: string[] = [GENERATED_MARKER, '', '# Change log', '', INTRO, ''];

	out.push('## Unreleased', '');
	if (set.unreleased.length === 0) {
		out.push('Nothing yet — no change note has been recorded since the last release.', '');
	} else {
		out.push('Merged since the last release; these ship with the next one.', '');
	}
	out.push(...renderFragments(set.unreleased));
	out.push(...renderWireContract(unreleasedWc));

	const releases = [...set.releases].sort((a, b) =>
		compareVersions(b.release.version, a.release.version),
	);
	for (const { release, fragments } of releases) {
		const range = release.from === null ? release.to : `${release.from}..${release.to}`;
		out.push(`## ${release.version} — ${release.date}`, '');
		out.push(`${release.commits} commits: \`git log --no-merges ${range}\``, '');
		out.push(...renderFragments(fragments));
		out.push(...renderWireContract(release.wire_contract));
	}

	return `${out.join('\n').replace(/\n+$/, '')}\n`;
}

