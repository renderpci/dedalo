/**
 * ROOT'S HOST-MAP RENDERER (src/rules/host_map_main.ts runHostMap + src/rules/host_map.ts), run
 * as the non-root suite on macOS and Linux.
 *
 * SEAMS (named, spec §9): every directory is a scratch PARAMETER under .test-tmp/ (map dir, locks
 * dir, identities file); uids are MODELLED through an injected lstat (the real fs answers, a
 * per-path override gives a file a foreign uid — no account is created, nothing is chowned); the
 * host web lock is a fake LockIo writing to the same call log as the fake nginx exec, so "the lock
 * is taken and released on every path" and "configtest runs inside it" are observed.
 */
